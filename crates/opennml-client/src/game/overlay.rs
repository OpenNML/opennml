    /// Smoke test without window: shadow (black, y + 2) under the text (x + 2) in the image.
    #[test]
    fn overlay_draws_shadow_and_text_offscreen() {
        use opennml_render::{BackendChoice, CAPTURE_FORMAT, headless_device, render_to_image};
        let Ok((device, queue, _)) = headless_device(BackendChoice::Auto) else {
            eprintln!("no GPU, test skipped");
            return;
        };
        let vfs = panel_vfs(PANEL_LOC);
        let mut text =
            OverlayText::new(&device, CAPTURE_FORMAT, &vfs.vfs, "DEU", 1024, None).unwrap();
        assert_eq!(text.line_height(), 15);
        let lines = [OverlayLine {
            x: 4,
            y: 4,
            text: "A".into(),
            color: 0xFFFF_0000,
        }];
        let img = render_to_image(
            &device,
            &queue,
            (40, 40),
            CAPTURE_FORMAT,
            |encoder, view| {
                text.draw(&device, &queue, encoder, view, (40, 40), &lines);
            },
        )
        .unwrap();
        // Text [6, 4, 22, 20], shadow [4, 6, 20, 22]: only text, only shadow, both, nothing.
        assert_eq!(img.get_pixel(21, 5).0, [255, 0, 0, 255]);
        assert_eq!(img.get_pixel(5, 21).0, [0, 0, 0, 255]);
        assert_eq!(img.get_pixel(12, 12).0, [255, 0, 0, 255]);
        assert_eq!(img.get_pixel(35, 35).0[3], 0);
    }
