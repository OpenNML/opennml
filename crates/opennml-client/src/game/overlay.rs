/// Colors as ARGB (`0xAARRGGBB`, diffuse of the draw commands).
const WHITE: u32 = 0xFFFF_FFFF;
const YELLOW: u32 = 0xFFFF_E64D;
const GRAY: u32 = 0xFFCC_CCCC;

/// Font of the overlay: `PanelInfo` (Arial, 15 px fixed, `localisation.*`; re/ui-rendering 3.2), atlas
/// `data/fonts/arial_15_0_0_0_0`.
pub const PANEL_FONT: &str = "PanelInfo";

/// Offset of the shadow in pixels (`FUN_0055F8C0`, re/ui-rendering 3.8.5): shadow at `(x, y + 2)`, text at
/// `(x + 2, y)`.
const SHADOW_OFFSET: i32 = 2;

/// An overlay line: top left corner in pixels, text, color as ARGB.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OverlayLine {
    pub x: i32,
    pub y: i32,
    pub text: String,
    pub color: u32,
}

/// Overlaid text of the viewer via the font runtime of `opennml-ui`: the font `PanelInfo` from the
/// installation, drawn with the shadow of the original (no text layout: overlay texts may contain `[`,
/// every line goes through `draw_string` unchanged). A [`UiRenderer`] belongs to exactly these `assets`.
pub struct OverlayText {
    pub assets: UiAssets,
    pub fonts: FontBook,
    pub renderer: UiRenderer,
    panel: FontRef,
}

/// Loads images and font `PanelInfo` (without GPU). The overlay does not need the other fonts of the language file
/// and they are not loaded; missing atlases are generated by `generator`.
pub fn load_panel_font(
    vfs: &Vfs,
    language_tag: &str,
    screen_width: u32,
    generator: Option<&dyn AtlasGenerator>,
) -> Result<(UiAssets, FontBook, FontRef)> {
    let mut loc = load_localisation(vfs, language_tag).map_err(anyhow::Error::msg)?;
    loc.fonts.retain(|font| font.name == PANEL_FONT);
    loc.icons.clear();
    if loc.fonts.is_empty() {
        bail!("font \"{PANEL_FONT}\" missing from the language file");
    }
    let mut assets = UiAssets::new();
    let width = i32::try_from(screen_width).unwrap_or(i32::MAX);
    let fonts = FontBook::load(vfs, &loc, width, &mut assets, generator);
    let panel = fonts.by_name(PANEL_FONT);
    Ok((assets, fonts, panel))
}

/// Draw commands of the lines: per line first the shadow at `(x, y + 2)` in `color & 0xFF000000`, then the
/// text at `(x + 2, y)` (`FUN_0055F8C0`, re/ui-rendering 3.8.5).
pub fn overlay_commands(fonts: &FontBook, panel: FontRef, lines: &[OverlayLine]) -> Vec<DrawCmd> {
    let mut cmds = Vec::new();
    for line in lines {
        let codes = atlas_codes(&line.text);
        let shadow = line.color & 0xFF00_0000;
        draw_string(
            &codes,
            [line.x, line.y + SHADOW_OFFSET],
            shadow,
            panel,
            fonts,
            &mut cmds,
        );
        draw_string(
            &codes,
            [line.x + SHADOW_OFFSET, line.y],
            line.color,
            panel,
            fonts,
            &mut cmds,
        );
    }
    cmds
}

impl OverlayText {
    /// Creates font and drawer. `screen_width` is the width at start (relative fonts; `PanelInfo`
    /// is fixed and independent of it). Missing atlases are generated by `generator` (in the program
    /// `crate::ui_layer::atlas_generator`, none in tests: never into the user's cache).
    pub fn new(
        device: &wgpu::Device,
        format: wgpu::TextureFormat,
        vfs: &Vfs,
        language_tag: &str,
        screen_width: u32,
        generator: Option<&dyn AtlasGenerator>,
    ) -> Result<Self> {
        let (assets, fonts, panel) = load_panel_font(vfs, language_tag, screen_width, generator)
            .context("loading the overlay font")?;
        Ok(Self {
            assets,
            fonts,
            renderer: UiRenderer::new(device, format),
            panel,
        })
    }

    /// Line height of the font (largest glyph height of the `.fnt`).
    pub fn line_height(&self) -> i32 {
        self.fonts.font(self.panel).max_height
    }

    /// Draws the lines over the existing image (`LoadOp::Load`).
    pub fn draw(
        &mut self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        encoder: &mut wgpu::CommandEncoder,
        target: &wgpu::TextureView,
        size: (u32, u32),
        lines: &[OverlayLine],
    ) {
        let cmds = overlay_commands(&self.fonts, self.panel, lines);
        self.renderer
            .draw(device, queue, encoder, target, size, &self.assets, &cmds);
    }
}

/// Everything the overlay shows.
#[derive(Debug, Clone, PartialEq)]
pub struct OverlayInfo {
    pub fps: u32,
    pub backend: String,
    pub adapter: String,
    pub level: String,
    pub tiles: (u32, u32),
    pub objects: usize,
    /// Distance, pitch (degrees), target x/z; `None` for a free camera.
    pub camera: Option<(f32, f32, f32, f32)>,
    pub aspect: AspectSetting,
    pub fog: bool,
    /// Light and weather ([`environment_line`]).
    pub environment: String,
    /// Shadows ([`shadow_line`]).
    pub shadows: String,
    /// Effects ([`effect_line`]).
    pub effects: String,
    /// Sound ([`audio_line`]).
    pub audio: String,
    /// Simulation (`SimHost::status_line`).
    pub sim: String,
    /// Account of the active player (`SimHost::account_line`); `None` without simulation.
    pub account: Option<String>,
    /// Standing messages of the active player with their color (`GameSession::message_lines`: heads of the
    /// message bar, then the text messages of the screen texts); empty if the viewer draws the game UI (`--hud`).
    pub messages: Vec<(String, u32)>,
    /// Command UI: right-click action under the mouse or build site in placement mode
    /// (`economy::action_line`, `economy::placement_line`).
    pub economy: Vec<String>,
    /// Combat values of the first selected object or of the object under the mouse
    /// (`combat_calc::combat_line`).
    pub combat: Option<String>,
    /// Description of the object under the mouse.
    pub hovered: Option<String>,
    pub help: bool,
}

