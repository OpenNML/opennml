/// Overlay line for light (`level` or name of the preset) and weather with the number of
/// drawn particles.
pub fn environment_line(light: &str, weather: Option<WeatherKind>, drawn: u32) -> String {
    let light = if light == LEVEL_LIGHT_NAME {
        "level (.wld)"
    } else {
        light
    };
    let weather = match weather {
        None => "off".to_string(),
        Some(WeatherKind::Rain) => format!("rain ({drawn} particles)"),
        Some(WeatherKind::Snow) => format!("snow ({drawn} particles)"),
    };
    format!("Light: {light} | Weather: {weather}")
}

/// Overlay line of the shadows: stage, drawn decals, ground planes and texture shadows,
/// atlas occupancy.
pub fn shadow_line(quality: u8, stats: &ShadowStats) -> String {
    format!(
        "Shadows: stage {quality} | {} decals, {} ground planes, kind 2: {}, kind 3: {} | atlas {:.0}/{}",
        stats.decals + stats.specials,
        stats.groundplanes,
        stats.persistent,
        stats.per_frame,
        stats.atlas_used.ceil(),
        stats.atlas_capacity
    )
}

/// Overlay line of the effects: stage, own effects of the objects, world effects, ambient effects,
/// particles, frozen effects, drawn quads and models.
pub fn effect_line(quality: u8, counts: &EffectCounts, quads: usize, models: usize) -> String {
    format!(
        "Effects: stage {quality} | {} on objects, {} world | surf {}, fish {}, eagles {} | {} particles, {} frozen | {quads} quads, {models} models",
        counts.owned,
        counts.world,
        counts.surf,
        counts.fish,
        counts.eagles,
        counts.particles,
        counts.frozen
    )
}

/// Overlay line of the sound: running music with the status of the state machine, combat music switch, number of
/// voices, muting and recording.
pub fn audio_line(
    music: Option<&str>,
    status: &str,
    attack: bool,
    voices: usize,
    mute: bool,
    capture: bool,
) -> String {
    let music = music.map_or("-".to_string(), |path| {
        path.rsplit(['/', '\\']).next().unwrap_or(path).to_string()
    });
    let mut line = format!(
        "Sound: music {music} ({status}) | combat music {} | {voices} voices",
        if attack { "on" } else { "off" }
    );
    if mute {
        line.push_str(" | muted");
    }
    if capture {
        line.push_str(" | recording");
    }
    line
}

/// Lines of the overlay; `line_height` from the font.
pub fn overlay_lines(info: &OverlayInfo, line_height: i32) -> Vec<OverlayLine> {
    let mut texts: Vec<(String, u32)> = vec![
        (
            format!("{} FPS | {} | {}", info.fps, info.backend, info.adapter),
            WHITE,
        ),
        (
            format!(
                "{} | {} x {} tiles | {} objects",
                info.level, info.tiles.0, info.tiles.1, info.objects
            ),
            WHITE,
        ),
    ];
    let aspect = match info.aspect {
        AspectSetting::Correct => "undistorted",
        AspectSetting::Original43 => "like 4:3",
        AspectSetting::Stretch => "stretched (original)",
    };
    let fog = if info.fog { "on" } else { "off" };
    texts.push(match info.camera {
        Some((distance, pitch, x, z)) => (
            format!(
                "Camera: distance {distance:.0}, pitch {pitch:.1} degrees, target ({x:.0}, {z:.0}) | Image: {aspect} | Fog: {fog}"
            ),
            WHITE,
        ),
        None => (format!("Free camera | Image: {aspect} | Fog: {fog}"), WHITE),
    });
    texts.push((info.environment.clone(), WHITE));
    texts.push((info.shadows.clone(), WHITE));
    texts.push((info.effects.clone(), WHITE));
    texts.push((info.audio.clone(), WHITE));
    texts.push((info.sim.clone(), WHITE));
    if let Some(account) = &info.account {
        texts.push((account.clone(), WHITE));
    }
    texts.extend(info.messages.iter().cloned());
    texts.extend(info.economy.iter().map(|l| (l.clone(), YELLOW)));
    texts.extend(info.combat.iter().map(|l| (l.clone(), YELLOW)));
    texts.push(match &info.hovered {
        Some(text) => (format!("Under the mouse: {text}"), YELLOW),
        None => ("Under the mouse: -".into(), GRAY),
    });
    if info.help {
        texts.extend(HELP.iter().map(|h| (h.to_string(), GRAY)));
    } else {
        texts.push(("F1: Help".into(), GRAY));
    }
    layout_lines(texts, line_height)
}

/// Help in the model browser.
pub const BROWSER_HELP: &str = "Left/Right: model (Shift: 10) | Up/Down: animation | Space: pause | F8: shadow kind | V: preview | -/+: burn intensity | T/Enter: sound | left mouse button: rotate | mouse wheel: zoom | B: map";

/// Lines of the model browser: frame rate, description, help.
pub fn browser_lines(
    fps: u32,
    backend: &str,
    describe: Vec<String>,
    line_height: i32,
) -> Vec<OverlayLine> {
    titled_lines(
        &format!("{fps} FPS | {backend} | Model browser"),
        describe,
        BROWSER_HELP,
        line_height,
    )
}

/// Help in the effect browser.
pub const EFFECT_HELP: &str = "Left/Right: effect (Shift: 10) | Space: restart | -/+: radius (.hef) | left mouse button: rotate | mouse wheel: zoom | N: map";

/// Lines of the effect browser: frame rate, description, help.
pub fn effect_lines(
    fps: u32,
    backend: &str,
    describe: Vec<String>,
    line_height: i32,
) -> Vec<OverlayLine> {
    titled_lines(
        &format!("{fps} FPS | {backend} | Effect browser"),
        describe,
        EFFECT_HELP,
        line_height,
    )
}

fn titled_lines(
    title: &str,
    describe: Vec<String>,
    help: &str,
    line_height: i32,
) -> Vec<OverlayLine> {
    let mut texts = vec![(title.to_string(), WHITE)];
    texts.extend(describe.into_iter().map(|t| (t, WHITE)));
    texts.push((help.into(), GRAY));
    layout_lines(texts, line_height)
}

/// Places texts one below the other from the top left corner.
pub fn layout_lines(texts: Vec<(String, u32)>, line_height: i32) -> Vec<OverlayLine> {
    texts
        .into_iter()
        .enumerate()
        .map(|(i, (text, color))| OverlayLine {
            x: 8,
            y: 8 + i as i32 * (line_height + 2),
            text,
            color,
        })
        .collect()
}

