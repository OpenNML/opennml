    /// `--dialog options,videooptions` in the window is operable. After the fly-in a real click (move,
    /// press, release through `MenuHost`) on `OPTIONS/SOUNDOPTIONS` switches the subpage; without a GPU
    /// device.
    #[test]
    fn dialog_window_is_live() {
        let Some(dir) = nml_rda::testutil::corpus_game_dir() else {
            return;
        };
        let vfs = Vfs::open_game_dir(&dir).unwrap();
        let mut audio = silent(&vfs);
        let mut menu = DialogMenu::new(
            &vfs,
            &names(&["options", "videooptions"]),
            1024,
            None,
            None,
            &audio,
            Vec::new(),
        )
        .unwrap();
        let mut now = 0;
        settle(&mut menu, &vfs, &mut audio, &mut now);
        assert_eq!(
            menu.host.app.menu().open_names(),
            ["options", "videooptions"]
        );
        let report = menu.host.app.report(S1024, now);
        assert!(report.dialogs.iter().all(|d| !d.animating), "fly-in over");
        click(&mut menu, "options", "soundoptions", now);
        settle(&mut menu, &vfs, &mut audio, &mut now);
        // SOUNDOPTIONS is on top. VIDEOOPTIONS stays open: `--dialog` does not open it through its button, so
        // the flag of the open subpage is empty, and `OPTIONS` closes `""` (O-103, "frame opened").
        assert_eq!(
            menu.host.app.menu().open_names(),
            ["options", "videooptions", "soundoptions"]
        );
        assert!(menu.host.app.tree().find("SOUNDOPTIONS").is_some());
        assert_eq!(menu.title(), "OPTIONS,VIDEOOPTIONS,SOUNDOPTIONS");
        // Now SOUNDOPTIONS is remembered: the next subpage button closes it (outside the double click).
        now += 1000;
        click(&mut menu, "options", "gameplayoptions", now);
        settle(&mut menu, &vfs, &mut audio, &mut now);
        assert!(menu.host.app.tree().find("SOUNDOPTIONS").is_none());
        assert_eq!(
            menu.host.app.menu().open_names().last().map(String::as_str),
            Some("gameplayoptions")
        );
    }

