//! Dialog browser of the viewer (`--dialog`).
//!
//! **Screenshot** (`--dialog ... --screenshot`): the dialogs of the installation static
//! (`nml_ui::dialog::paint_static`, state of the file, `DIALOG_DRAW_GOLDEN`). Structure:
//! [`DialogScene`] is the CPU core without `wgpu` (library, UI layer [`UiLayer`] with fonts, texts
//! and images, draw commands per target size) and runs in tests without a GPU; [`DialogBrowser`] adds
//! the [`UiRenderer`] (a renderer belongs to exactly one `UiAssets`).
//!
//! **Window**: the dialogs are operable. [`DialogMenu`] is the GPU-free core over the menu host
//! (`MenuHost`, `MenuApp` without a start sequence, the dialogs of the list in order with `open_by_name`);
//! [`DialogLayer`] adds the renderer. As long as the layer is visible and a dialog is open, mouse and keys go
//! to the UI; Ctrl+Page Up/Down and Ctrl+D stay keys of the viewer.
//!
//! The fonts arise once with the width at the start (O-58, `FontBook::load`), the position of the dialogs
//! follows every window size (conversion from the 1280 x 1024 grid). Loading happens with
//! `is_menu_level = false` (like the reference images with `Engine.ini` `IsMenuLevel 0`).

