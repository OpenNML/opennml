    /// Lets the UI run until nothing is queued and no transition is running (at most 10 s).
    fn settle(menu: &mut DialogMenu, vfs: &Vfs, audio: &mut dyn MenuAudio, now: &mut u64) {
        for _ in 0..625 {
            menu.advance(vfs, S1024, *now, audio);
            *now += 16;
            if menu.host.app.queue().is_empty() && !menu.host.app.menu().busy() {
                return;
            }
        }
        panic!("UI does not settle");
    }

