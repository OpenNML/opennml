/// Keys of the dialog browser in the window (with Ctrl held): Page Down next, Page Up previous dialog of the
/// library (reopened), D hides or shows the layer.
pub const KEY_NEXT: KeyCode = KeyCode::PageDown;
pub const KEY_PREVIOUS: KeyCode = KeyCode::PageUp;
pub const KEY_TOGGLE: KeyCode = KeyCode::KeyD;

/// Reads language file, texts and all `.dlg` (without GPU, without images and fonts).
fn open_library(vfs: &Vfs) -> Result<DialogLibrary> {
    let loc = load_localisation(vfs).map_err(anyhow::Error::msg)?;
    let texts = Texts::load(vfs, &loc);
    Ok(DialogLibrary::load(vfs, &texts, false))
}

/// Checks the given names against the library and returns them in the spelling of the library (case as in
/// `FUN_004E24F0`). Errors: unknown name, map entry without a file, file without a widget, empty list.
fn resolve_names(library: &DialogLibrary, names: &[String]) -> Result<Vec<String>> {
    if names.is_empty() {
        bail!("no dialog given");
    }
    names
        .iter()
        .map(|name| {
            library.find(name).map_err(anyhow::Error::msg)?;
            Ok(upper_word(name))
        })
        .collect()
}

/// Checks the names of `--dialog` before the window or GPU is created.
pub fn check_names(vfs: &Vfs, names: &[String]) -> Result<()> {
    let library = open_library(vfs).context("loading dialogs")?;
    resolve_names(&library, names).map(|_| ())
}

/// CPU core of the static dialog browser (`--screenshot`): library, UI layer (fonts, texts, images) and the
/// draw commands of the opened dialogs (cached per target size).
pub struct DialogScene {
    library: DialogLibrary,
    /// Opened dialogs in opening order (names as in the library).
    stack: Vec<String>,
    layer: UiLayer,
    cache: Option<((u32, u32), Vec<DrawCmd>)>,
}

impl DialogScene {
    /// Loads library, fonts (width `screen_width` for relative sizes, only now: O-58) and texts and opens
    /// `names` in this order. Missing atlases are generated by `generator` (`None`: fallback).
    pub fn new(
        vfs: &Vfs,
        names: &[String],
        screen_width: u32,
        generator: Option<&dyn AtlasGenerator>,
    ) -> Result<Self> {
        let layer = UiLayer::new(vfs, screen_width, generator).context("loading dialogs")?;
        let library = DialogLibrary::load(vfs, &layer.texts, false);
        let stack = resolve_names(&library, names)?;
        Ok(Self {
            library,
            stack,
            layer,
            cache: None,
        })
    }

    /// Names of the opened dialogs, separated by commas (log).
    pub fn title(&self) -> String {
        self.stack.join(",")
    }

    /// Pixel height of the font `name` (the one chosen at the start, O-58).
    #[cfg(test)]
    pub fn font_px(&self, name: &str) -> i32 {
        let fonts = &self.layer.fonts;
        fonts.font(fonts.by_name(name)).px
    }

    /// Origin of the atlas of the font `name` (installation, generated, fallback).
    #[cfg(test)]
    pub fn font_source(&self, name: &str) -> AtlasSource {
        let fonts = &self.layer.fonts;
        fonts.font(fonts.by_name(name)).source
    }

    /// Images of the UI (textures of the draw commands).
    #[cfg(test)]
    pub fn assets(&self) -> &UiAssets {
        &self.layer.assets
    }

    /// Draw commands for a target of size `size` (from the cache as long as size and opened dialogs stay
    /// the same). Size 0 (minimized window) yields nothing. A dialog without a widget is skipped with a
    /// note in the log.
    pub fn commands(&mut self, vfs: &Vfs, size: (u32, u32)) -> &[DrawCmd] {
        if size.0 == 0 || size.1 == 0 {
            return &[];
        }
        if self
            .cache
            .as_ref()
            .is_none_or(|(cached, _)| *cached != size)
        {
            let mut widgets: Vec<&WidgetDesc> = Vec::new();
            for name in &self.stack {
                match self.library.find(name) {
                    Ok(widget) => widgets.push(widget),
                    Err(e) => log::warn!("{e}"),
                }
            }
            let mut ctx = self.layer.context(vfs, screen_of(size));
            let cmds = paint_static(&widgets, &mut ctx);
            self.cache = Some((size, cmds));
        }
        self.cache.as_ref().map_or(&[], |(_, cmds)| cmds.as_slice())
    }
}

/// Static dialog browser without a window (`--dialog ... --screenshot`): [`DialogScene`] plus renderer.
pub struct DialogBrowser {
    scene: DialogScene,
    renderer: UiRenderer,
}

impl DialogBrowser {
    /// Loads everything and creates the renderer for `format`; `screen_width` is the width at the start.
    /// Missing atlases are generated by `generator` (in the viewer `nml_client::ui_layer::atlas_generator`).
    pub fn new(
        vfs: &Vfs,
        device: &wgpu::Device,
        format: wgpu::TextureFormat,
        names: &[String],
        screen_width: u32,
        generator: Option<&dyn AtlasGenerator>,
    ) -> Result<Self> {
        Ok(Self {
            scene: DialogScene::new(vfs, names, screen_width, generator)?,
            renderer: UiRenderer::new(device, format),
        })
    }

    pub fn title(&self) -> String {
        self.scene.title()
    }

    /// Draws the dialogs over the existing image (`LoadOp::Load`).
    pub fn draw(
        &mut self,
        vfs: &Vfs,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        encoder: &mut wgpu::CommandEncoder,
        target: &wgpu::TextureView,
        size: (u32, u32),
    ) {
        self.scene.commands(vfs, size);
        // Only after building the commands (they load images into `assets`) fetch the shared references.
        let Some((_, cmds)) = self.scene.cache.as_ref() else {
            return;
        };
        self.scene.layer.draw(
            &mut self.renderer,
            device,
            queue,
            encoder,
            target,
            size,
            cmds,
        );
    }
}

/// Next index on Ctrl+Page Down (`delta = 1`) or Ctrl+Page Up (`-1`) among `count` dialogs, wrapping
/// around; 0 without dialogs.
pub fn step_index(count: usize, index: usize, delta: i32) -> usize {
    if count == 0 {
        return 0;
    }
    let count = count as i64;
    (index as i64 + i64::from(delta)).rem_euclid(count) as usize
}

/// Options of the host for the dialog browser: no start sequence, raw display modes of the monitor, the
/// driver list of the sound system.
fn menu_options(display_modes: &[DisplayMode], audio: &dyn MenuAudio) -> MenuOptions {
    MenuOptions {
        display_modes: display_modes.to_vec(),
        sound_drivers: audio.sound_drivers(),
        start_menu: false,
        ..MenuOptions::default()
    }
}

/// Operable dialog browser in the window, GPU-free: menu host, the draw commands of the last logic step
/// (without pointer 7: the viewer keeps the system pointer) and the visibility (Ctrl+D).
///
/// Settings: a file only with `--settings` (checked with `settings::settings_path_for`, never in the
/// installation), written only when a dialog asks for it (`OPTIONS OK`); without the switch the defaults
/// including `defaultkeys.ini` only in memory, nothing is ever saved then. Writing at program end (O-32)
/// belongs to `nml-game`; the viewer keeps `nml-viewer.toml`.
pub struct DialogMenu {
    pub host: MenuHost,
    /// Index of the last opened dialog in the library (starting point for [`Self::step`]).
    index: usize,
    /// Raw display modes for rebuilding the UI.
    display_modes: Vec<DisplayMode>,
    cmds: Vec<DrawCmd>,
    visible: bool,
}

impl DialogMenu {
    /// Loads layer (fonts with `screen_width`, O-58), settings from `settings` (`None`: defaults only in
    /// memory) and the UI and queues `names` for opening in this order (`MenuApp::open_by_name`; they are
    /// opened in the following frames, each dialog with its fly-in). Unknown names are an error as with the
    /// screenshot.
    pub fn new(
        vfs: &Vfs,
        names: &[String],
        screen_width: u32,
        generator: Option<&dyn AtlasGenerator>,
        settings: Option<PathBuf>,
        audio: &dyn MenuAudio,
        display_modes: Vec<DisplayMode>,
    ) -> Result<Self> {
        let layer = UiLayer::new(vfs, screen_width, generator).context("loading dialogs")?;
        let mut config = match &settings {
            Some(path) => load_settings(path, vfs),
            None => {
                log::info!(
                    "Dialog layer without --settings: defaults and defaultkeys.ini only in memory, nothing is \
                     saved"
                );
                default_config(vfs)
            }
        };
        // The viewer always loads the dialogs in the version without a menu level; the saved value is kept for
        // the host for writing back.
        let saved_menu_level = std::mem::replace(&mut config.is_menu_level, false);
        let opts = menu_options(&display_modes, audio);
        let mut host = MenuHost::new(vfs, layer, config, opts, audio, settings)?;
        if saved_menu_level {
            host.keep_saved_menu_level(true);
        }
        let library = host.app.menu().library();
        let names = resolve_names(library, names)?;
        let index = names
            .last()
            .and_then(|top| library.names().iter().position(|n| n == top))
            .unwrap_or(0);
        for name in &names {
            host.app.open_by_name(name).map_err(anyhow::Error::msg)?;
        }
        Ok(Self {
            host,
            index,
            display_modes,
            cmds: Vec::new(),
            visible: true,
        })
    }

    /// A dialog is open or queued for opening.
    pub fn dialog_open(&self) -> bool {
        !self.host.app.menu().open_names().is_empty() || !self.host.app.queue().is_empty()
    }

    /// Mouse and keys belong to the UI: layer visible and a dialog open.
    pub fn takes_input(&self) -> bool {
        self.visible && self.dialog_open()
    }

    /// Window input without a character to the UI (`MenuHost::on_input`).
    pub fn on_input(&mut self, event: &InputEvent, screen: Screen, now: u64) {
        self.host.on_input(event, screen, now);
    }

    /// Key with a character to the UI (`MenuHost::on_key`).
    pub fn on_key(
        &mut self,
        code: KeyCode,
        pressed: bool,
        ch: Option<u16>,
        screen: Screen,
        now: u64,
    ) {
        self.host.on_key(code, pressed, ch, screen, now);
    }

    /// Focus loss: release all keys of the UI.
    pub fn release_keys(&mut self) {
        self.host.release_keys();
    }

    /// Logic step: one frame of the UI on `screen` at viewer clock `now`, then its effects (sound through the
    /// sound system of the viewer, settings file); what only the window can do comes back as a request.
    pub fn advance(
        &mut self,
        vfs: &Vfs,
        screen: Screen,
        now: u64,
        audio: &mut dyn MenuAudio,
    ) -> HostRequests {
        self.cmds = self.host.frame_cmds(vfs, screen, now);
        self.host.apply_effects(audio, vfs)
    }

    /// Draw commands of the last logic step.
    pub fn commands(&self) -> &[DrawCmd] {
        &self.cmds
    }

    /// Ctrl+Page Down (`delta = 1`) or Ctrl+Page Up (`-1`): a new UI with the current settings opens the next
    /// or previous dialog of the library in path order, alone (wrapping around).
    pub fn step(&mut self, delta: i32, vfs: &Vfs, audio: &dyn MenuAudio) -> Result<()> {
        let names = self.host.app.menu().library().names();
        if names.is_empty() {
            return Ok(());
        }
        let next = step_index(names.len(), self.index, delta);
        self.host
            .restart(vfs, menu_options(&self.display_modes, audio), audio)?;
        self.host
            .app
            .open_by_name(&names[next])
            .map_err(anyhow::Error::msg)?;
        self.index = next;
        self.cmds.clear();
        Ok(())
    }

    /// Opened dialogs in opening order, uppercase and separated by commas (window title).
    pub fn title(&self) -> String {
        let open = self.host.app.menu().open_names();
        open.iter()
            .map(|n| upper_word(n))
            .collect::<Vec<_>>()
            .join(",")
    }

    pub fn visible(&self) -> bool {
        self.visible
    }

    /// Ctrl+D: hide or show the layer.
    pub fn toggle(&mut self) {
        self.visible = !self.visible;
    }
}

/// Operable dialog layer of the window: [`DialogMenu`] plus renderer.
pub struct DialogLayer {
    pub menu: DialogMenu,
    renderer: UiRenderer,
}

impl DialogLayer {
    pub fn new(menu: DialogMenu, device: &wgpu::Device, format: wgpu::TextureFormat) -> Self {
        Self {
            menu,
            renderer: UiRenderer::new(device, format),
        }
    }

    /// Draws the commands of the last logic step over the existing image (`LoadOp::Load`); hidden:
    /// nothing. Screenshots of the control channel draw the same (without pointer).
    pub fn draw(
        &mut self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        encoder: &mut wgpu::CommandEncoder,
        target: &wgpu::TextureView,
        size: (u32, u32),
    ) {
        if !self.menu.visible {
            return;
        }
        let cmds = self.menu.commands();
        self.menu.host.layer.draw(
            &mut self.renderer,
            device,
            queue,
            encoder,
            target,
            size,
            cmds,
        );
    }

    /// The UI layer of the dialog layer (fonts, images, texts), also for the game UI (`--hud`).
    pub fn ui_layer_mut(&mut self) -> &mut UiLayer {
        &mut self.menu.host.layer
    }

    /// Draws foreign commands of the same layer (game UI, [`crate::hud_view`]) with the renderer of the
    /// dialog layer, regardless of whether the dialogs are hidden.
    pub fn draw_cmds(
        &mut self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        encoder: &mut wgpu::CommandEncoder,
        target: &wgpu::TextureView,
        size: (u32, u32),
        cmds: &[DrawCmd],
    ) {
        self.menu.host.layer.draw(
            &mut self.renderer,
            device,
            queue,
            encoder,
            target,
            size,
            cmds,
        );
    }
}

/// Who gets a pressed key when a dialog layer is present.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyRoute {
    /// Ctrl+Page Up/Down, Ctrl+D: key of the dialog browser (viewer).
    Browser,
    /// The UI (visible layer with an open dialog), also Esc.
    Menu,
    /// Esc with a hidden layer and an open dialog: nobody (the viewer does not end).
    Swallow,
    /// The viewer as without a dialog layer (then Esc ends it, but only without an open dialog).
    Viewer,
}

/// Route of a pressed key: Ctrl+Page Up/Down and Ctrl+D stay with the viewer; with a visible layer and an
/// open dialog the UI takes everything else; Esc ends the viewer only without an open dialog (in the
/// original Esc has no effect without an acceptor, re/menu-system 12.7).
pub fn route_key(code: KeyCode, ctrl_held: bool, visible: bool, dialog_open: bool) -> KeyRoute {
    if ctrl_held && matches!(code, KEY_NEXT | KEY_PREVIOUS | KEY_TOGGLE) {
        KeyRoute::Browser
    } else if visible && dialog_open {
        KeyRoute::Menu
    } else if code == KeyCode::Escape && dialog_open {
        KeyRoute::Swallow
    } else {
        KeyRoute::Viewer
    }
}

/// Keys that belong to the dialog browser when a dialog layer is present and Ctrl is held and are not
/// passed on as zoom (Page Up/Down) or camera (D).
pub fn strip_dialog_keys(keys: &mut HashSet<KeyCode>) {
    if keys.contains(&KeyCode::ControlLeft) || keys.contains(&KeyCode::ControlRight) {
        for key in [KEY_NEXT, KEY_PREVIOUS, KEY_TOGGLE] {
            keys.remove(&key);
        }
    }
}

