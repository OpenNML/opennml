    #[test]
    fn escape_never_ends_the_viewer_while_a_dialog_is_open() {
        use KeyCode::{Escape, KeyD, KeyW, PageDown};
        // Visible with an open dialog: Esc belongs to the UI.
        assert_eq!(route_key(Escape, false, true, true), KeyRoute::Menu);
        // Hidden with an open dialog: Esc has no effect, other keys belong to the viewer.
        assert_eq!(route_key(Escape, false, false, true), KeyRoute::Swallow);
        assert_eq!(route_key(KeyW, false, false, true), KeyRoute::Viewer);
        // Without an open dialog, Esc ends the viewer (visible or not).
        assert_eq!(route_key(Escape, false, true, false), KeyRoute::Viewer);
        assert_eq!(route_key(Escape, false, false, false), KeyRoute::Viewer);
        // Ctrl+Page Down and Ctrl+D stay viewer keys, also over open dialogs; without Ctrl they belong to the dialog.
        assert_eq!(route_key(PageDown, true, true, true), KeyRoute::Browser);
        assert_eq!(route_key(KeyD, true, false, true), KeyRoute::Browser);
        assert_eq!(route_key(PageDown, false, true, true), KeyRoute::Menu);
        assert_eq!(route_key(KeyW, true, true, true), KeyRoute::Menu);
    }

    /// A real click through the host: move, press, release on the center of the element.
    fn click(menu: &mut DialogMenu, dialog: &str, element: &str, now: u64) {
        let (x, y) = menu
            .host
            .app
            .element_center(dialog, element, S1024)
            .unwrap();
        for event in [
            InputEvent::CursorMoved {
                x: f64::from(x),
                y: f64::from(y),
            },
            InputEvent::Button {
                button: nml_client::keys::MouseButton::Left,
                pressed: true,
            },
            InputEvent::Button {
                button: nml_client::keys::MouseButton::Left,
                pressed: false,
            },
        ] {
            menu.on_input(&event, S1024, now);
        }
    }

