        assert!(menu.host.app.menu().open_names().is_empty());
        assert!(menu.takes_input());
        let mut now = 0;
        settle(&mut menu, &game.vfs, &mut audio, &mut now);
        assert_eq!(menu.title(), "TESTDLG,OTHER");
        assert!(!menu.commands().is_empty());
        // Ctrl+D: when hidden, mouse and keys belong to the viewer.
        menu.toggle();
        assert!(!menu.takes_input() && menu.dialog_open());
        menu.toggle();
        // Library in path order: OTHER (other.dlg) = 0, TESTDLG (test.dlg) = 1; top dialog = OTHER.
        menu.step(1, &game.vfs, &audio).unwrap();
        assert!(menu.commands().is_empty(), "the old frame is gone");
        settle(&mut menu, &game.vfs, &mut audio, &mut now);
        assert_eq!(menu.title(), "TESTDLG");
        menu.step(1, &game.vfs, &audio).unwrap();
        settle(&mut menu, &game.vfs, &mut audio, &mut now);
        assert_eq!(menu.title(), "OTHER", "wrapping around");
        assert_eq!(step_index(2, 0, -1), 1);
        assert_eq!(step_index(2, 1, -3), 0);
        assert_eq!(step_index(0, 5, 1), 0, "without dialogs");
